package io.github.ih0rd.codegen;

import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

import java.lang.reflect.Field;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.FileTime;
import java.util.Map;

import org.apache.maven.plugin.MojoExecutionException;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class PolyglotCodegenCheckMojoTest {

  @TempDir Path tempDir;

  @Test
  void checkPassesWhenGeneratedSourcesAreUpToDate() throws Exception {
    Path inputDirectory = Files.createDirectories(tempDir.resolve("scripts-ok"));
    Path outputDirectory = tempDir.resolve("generated-ok");
    Path script = inputDirectory.resolve("check_api.py");
    Files.writeString(
        script,
        """
        polyglot.export_value("CheckApi", CheckApi)

        class CheckApi:
            def ping(self) -> int:
                return 1
        """);

    PolyglotCodegenMojo generator = new PolyglotCodegenMojo();
    setField(generator, "inputDirectory", inputDirectory.toFile());
    setField(generator, "outputDirectory", outputDirectory.toFile());
    setField(generator, "basePackage", "com.example.polyglot");
    setField(generator, "projectGroupId", "com.example");
    setField(generator, "project", new org.apache.maven.project.MavenProject());
    generator.execute();

    PolyglotCodegenCheckMojo check = new PolyglotCodegenCheckMojo();
    setField(check, "inputDirectory", inputDirectory.toFile());
    setField(check, "outputDirectory", outputDirectory.toFile());
    setField(check, "basePackage", "com.example.polyglot");
    setField(check, "projectGroupId", "com.example");

    assertDoesNotThrow(check::execute);
  }

  @Test
  void checkFailsWhenGeneratedSourcesAreDrifted() throws Exception {
    Path inputDirectory = Files.createDirectories(tempDir.resolve("scripts-drift"));
    Path outputDirectory = tempDir.resolve("generated-drift");
    Path script = inputDirectory.resolve("check_api.py");
    Files.writeString(
        script,
        """
        polyglot.export_value("CheckApi", CheckApi)

        class CheckApi:
            def ping(self) -> int:
                return 1
        """);

    PolyglotCodegenMojo generator = new PolyglotCodegenMojo();
    setField(generator, "inputDirectory", inputDirectory.toFile());
    setField(generator, "outputDirectory", outputDirectory.toFile());
    setField(generator, "basePackage", "com.example.polyglot");
    setField(generator, "projectGroupId", "com.example");
    setField(generator, "project", new org.apache.maven.project.MavenProject());
    generator.execute();

    Path generatedSource = outputDirectory.resolve("com/example/polyglot/CheckApi.java");
    Files.writeString(generatedSource, Files.readString(generatedSource) + "\n// drift");

    PolyglotCodegenCheckMojo check = new PolyglotCodegenCheckMojo();
    setField(check, "inputDirectory", inputDirectory.toFile());
    setField(check, "outputDirectory", outputDirectory.toFile());
    setField(check, "basePackage", "com.example.polyglot");
    setField(check, "projectGroupId", "com.example");

    assertThrows(MojoExecutionException.class, check::execute);
  }

  @Test
  void checkPassesForUnchangedV040SourcesWithoutRewritingThem() throws Exception {
    Path inputDirectory = Files.createDirectories(tempDir.resolve("scripts-v040"));
    Path outputDirectory = Files.createDirectories(tempDir.resolve("generated-v040"));
    Files.writeString(
        inputDirectory.resolve("compatibility_api.py"),
        """
            class EmptyApi:
                pass

            polyglot.export_value("EmptyApi", EmptyApi)

            class MultiApi:
                def count(self) -> int:
                    return 1

                def name(self, key: str) -> str:
                    return key

            polyglot.export_value("MultiApi", MultiApi)

            class NestedApi:
                def transform(self, data: list[dict[str, float]]) -> dict[str, list[bool]]:
                    return {}

            polyglot.export_value("NestedApi", NestedApi)
            """);

    // Captured v0.4.0 sources: do not generate the expected files with the code under test.
    Map<String, String> sources =
        Map.of(
            "EmptyApi",
                """
            /**
             * This file was generated by polyglot-codegen.
             *
             * SHA-256 checksum: d2bb2b6c388699cda6ec8b75b838748a181be6bda6141c5b542682933f49dcf5
             *
             * Any manual changes will be overwritten.
             */
            package com.demo;

            public interface EmptyApi {

            }
            """,
            "MultiApi",
                """
            /**
             * This file was generated by polyglot-codegen.
             *
             * SHA-256 checksum: 3d803ff95927ab15972acfa7aa3851944cad55db3fc3af23fe23878c266b9f05
             *
             * Any manual changes will be overwritten.
             */
            package com.demo;

            public interface MultiApi {

                Integer count();
                String name(String key);
            }
            """,
            "NestedApi",
                """
            /**
             * This file was generated by polyglot-codegen.
             *
             * SHA-256 checksum: 6a20d957ed48de07a00d7932259746c0ebd7b762623c04cbe16e389af371d71e
             *
             * Any manual changes will be overwritten.
             */
            package com.demo;

            import java.util.List;
            import java.util.Map;

            public interface NestedApi {

                Map<String, List<Boolean>> transform(List<Map<String, Double>> data);
            }
            """);
    Path packageDirectory = Files.createDirectories(outputDirectory.resolve("com/demo"));
    FileTime originalModifiedTime = FileTime.fromMillis(1234567890000L);
    for (var entry : sources.entrySet()) {
      Path target = packageDirectory.resolve(entry.getKey() + ".java");
      Files.writeString(target, entry.getValue());
      Files.setLastModifiedTime(target, originalModifiedTime);
    }

    PolyglotCodegenCheckMojo check = new PolyglotCodegenCheckMojo();
    setField(check, "inputDirectory", inputDirectory.toFile());
    setField(check, "outputDirectory", outputDirectory.toFile());
    setField(check, "basePackage", "com.demo");
    setField(check, "projectGroupId", "com.demo");
    setField(check, "strictMode", true);

    assertDoesNotThrow(check::execute);
    assertDoesNotThrow(check::execute);
    for (var entry : sources.entrySet()) {
      Path target = packageDirectory.resolve(entry.getKey() + ".java");
      assertEquals(entry.getValue(), Files.readString(target));
      assertEquals(originalModifiedTime, Files.getLastModifiedTime(target));
    }
  }

  private static void setField(Object target, String name, Object value) throws Exception {
    Class<?> type = target.getClass();

    while (type != null) {
      try {
        Field field = type.getDeclaredField(name);
        field.setAccessible(true);
        field.set(target, value);
        return;
      } catch (NoSuchFieldException ignored) {
        type = type.getSuperclass();
      }
    }

    throw new NoSuchFieldException(name);
  }
}
