package io.github.ih0rd.codegen;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.Set;
import java.util.TreeSet;

import com.github.javaparser.ast.CompilationUnit;
import com.github.javaparser.ast.Modifier.Keyword;
import com.github.javaparser.ast.body.ClassOrInterfaceDeclaration;
import com.github.javaparser.ast.body.MethodDeclaration;
import com.github.javaparser.ast.expr.SimpleName;

import io.github.ih0rd.polyglot.model.ContractClass;
import io.github.ih0rd.polyglot.model.ContractMethod;
import io.github.ih0rd.polyglot.model.ContractParam;

/**
 * Renders Java interface source files from parsed contracts.
 *
 * <p>The generator is deterministic: it collects imports from the rendered types, sorts them, and
 * adds a checksum header for the generated interface body.
 */
public final class JavaInterfaceGenerator {

  private static final String NL = "\n";

  private static final String GENERATED_HEADER_TEMPLATE =
      "/**\n"
          + " * This file was generated by polyglot-codegen.\n"
          + " *\n"
          + " * SHA-256 checksum: ${checksum}\n"
          + " *\n"
          + " * Any manual changes will be overwritten.\n"
          + " */\n";
  private final JavaTypeRenderer renderer = new JavaTypeRenderer();
  private final JavaContractValidator validator = new JavaContractValidator();

  /** Creates a generator for deterministic Java interface rendering. */
  public JavaInterfaceGenerator() {
    // The renderer field is initialized eagerly for reuse across generations.
  }

  /**
   * Generates a complete Java source file for the given contract.
   *
   * @param contract parsed contract model to render
   * @param basePackage base Java package for the generated interface
   * @return complete Java source file contents
   */
  public String generate(ContractClass contract, String basePackage) {

    CompilationUnit compilationUnit = generateAst(contract, basePackage);
    ClassOrInterfaceDeclaration javaInterface =
        compilationUnit
            .getInterfaceByName(contract.name())
            .orElseThrow(
                () ->
                    new IllegalStateException(
                        "Generated AST is missing interface: " + contract.name()));
    // Preserve the v0.4.0 layout: a blank line after '{', but none between methods.
    StringBuilder interfaceBody =
        new StringBuilder("public interface ")
            .append(javaInterface.getNameAsString())
            .append(" {")
            .append(NL)
            .append(NL);
    for (MethodDeclaration method : javaInterface.getMethods()) {
      interfaceBody.append("    ").append(method).append(NL);
    }
    interfaceBody.append("}").append(NL);

    StringBuilder source =
        new StringBuilder(
            GENERATED_HEADER_TEMPLATE.replace("${checksum}", sha256(interfaceBody.toString())));
    source
        .append("package ")
        .append(compilationUnit.getPackageDeclaration().orElseThrow().getNameAsString())
        .append(";")
        .append(NL)
        .append(NL);
    compilationUnit
        .getImports()
        .forEach(
            declaration ->
                source
                    .append("import ")
                    .append(declaration.getNameAsString())
                    .append(";")
                    .append(NL));
    if (!compilationUnit.getImports().isEmpty()) {
      source.append(NL);
    }
    return source.append(interfaceBody).toString();
  }

  /**
   * Generates a JavaParser AST for a Java contract interface.
   *
   * <p>This is intentionally public so build integrations and tests can inspect the generated AST
   * without scraping Java source text.
   *
   * @param contract parsed contract
   * @param basePackage target Java package
   * @return Java source AST
   */
  public CompilationUnit generateAst(ContractClass contract, String basePackage) {
    validator.validate(contract, basePackage);

    CompilationUnit compilationUnit = new CompilationUnit();
    compilationUnit.setPackageDeclaration(basePackage);
    addImports(compilationUnit, contract);
    renderInterface(compilationUnit, contract);
    return compilationUnit;
  }

  /** Calculates the SHA-256 checksum stored in the generated file header. */
  private String sha256(String content) {
    try {
      MessageDigest digest = MessageDigest.getInstance("SHA-256");
      byte[] hash = digest.digest(content.getBytes(StandardCharsets.UTF_8));
      StringBuilder hexString = new StringBuilder();
      for (byte b : hash) {
        String hex = Integer.toHexString(0xff & b);
        if (hex.length() == 1) {
          hexString.append('0');
        }
        hexString.append(hex);
      }
      return hexString.toString();
    } catch (NoSuchAlgorithmException e) {
      throw new IllegalStateException("SHA-256 algorithm not available", e);
    }
  }

  private void addImports(CompilationUnit compilationUnit, ContractClass contract) {
    Set<Class<?>> imports =
        new TreeSet<>((left, right) -> left.getName().compareTo(right.getName()));
    for (ContractMethod method : contract.methods()) {
      renderer.collectImports(method.returnType(), imports);
      for (ContractParam param : method.params()) {
        renderer.collectImports(param.type(), imports);
      }
    }
    for (Class<?> importType : imports) {
      compilationUnit.addImport(importType);
    }
  }

  /** Renders one Java interface from the validated contract model. */
  private void renderInterface(CompilationUnit compilationUnit, ContractClass contract) {
    ClassOrInterfaceDeclaration type =
        compilationUnit.addInterface(contract.name(), Keyword.PUBLIC);
    for (ContractMethod method : contract.methods()) {
      type.addMember(renderMethod(method));
    }
  }

  /** Renders one Java method declaration. */
  private MethodDeclaration renderMethod(ContractMethod method) {
    MethodDeclaration methodDeclaration = new MethodDeclaration();
    methodDeclaration.setName(new SimpleName(method.name()));
    methodDeclaration.setType(renderer.renderAst(method.returnType()));
    methodDeclaration.removeBody();

    for (ContractParam param : method.params()) {
      methodDeclaration.addParameter(renderer.renderAst(param.type()), param.name());
    }

    return methodDeclaration;
  }
}
